package io.github.domovou69.scalelab

import android.app.Activity
import android.os.Build
import android.os.Bundle
import android.os.SystemClock
import android.util.Log
import android.util.TypedValue
import android.view.View
import android.view.ViewGroup
import android.view.ViewTreeObserver
import android.view.WindowInsets
import android.widget.Button
import android.widget.EditText
import android.widget.FrameLayout
import android.widget.LinearLayout
import android.widget.TextView
import org.json.JSONArray
import org.json.JSONObject

// The benchmark screen, rendered from assets/scale.json (generated by bench/make-scale.js).
//   --es screen scale|deep   the Checkout page with background layers, or the depth-check chain
//   --ei load 100|500|1000|2000   which background groups are stacked under Checkout
// Every view gets an exact pixel size (no wrap_content, no weights): a box splits its height between
// its children by `w`, a row its width, a grid box places children in `cols` columns. Content is padded
// by the system-bar insets: under edge-to-edge, views behind the status bar drop out of the tree.
class ScaleActivity : Activity() {
    private var markerH = 0
    private val ids = HashMap<String, Int>() // getIdentifier is a slow lookup; ~440 names, ~1000 uses

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        val t0 = SystemClock.uptimeMillis()
        val spec = JSONObject(assets.open("scale.json").bufferedReader().use { it.readText() })
        val (w, h, pad) = contentArea()
        markerH = h / 25
        val root = FrameLayout(this).apply {
            setPadding(pad[0], pad[1], pad[2], pad[3])
            isFocusableInTouchMode = true // keeps the EditTexts unfocused: no keyboard, no blinking cursor
        }
        if (intent.getStringExtra("screen") == "deep") {
            root.addView(build(JSONObject().put("t", "box").put("k", spec.getJSONArray("deep")), w, h))
        } else {
            val load = intent.getIntExtra("load", 100)
            val groups = spec.getJSONObject("groups")
            val wanted = listOf("g4" to 2000, "g3" to 1000, "g2" to 500, "g1" to 0).filter { load >= it.second }
            for ((g, _) in wanted) {
                val layers = groups.getJSONArray(g)
                for (i in 0 until layers.length()) root.addView(build(layers.getJSONObject(i), w, h))
            }
        }
        setContentView(root)
        root.requestFocus()
        val built = SystemClock.uptimeMillis() - t0
        window.decorView.viewTreeObserver.addOnDrawListener(object : ViewTreeObserver.OnDrawListener {
            var logged = false
            override fun onDraw() {
                if (logged) return
                logged = true
                Log.i("ScaleLab", "built $built ms, first draw ${SystemClock.uptimeMillis() - t0} ms")
            }
        })
    }

    // width, height and padding (left, top, right, bottom) of the area inside the system bars
    private fun contentArea(): Triple<Int, Int, IntArray> {
        if (Build.VERSION.SDK_INT >= 30) {
            val m = windowManager.currentWindowMetrics
            val i = m.windowInsets.getInsets(WindowInsets.Type.systemBars() or WindowInsets.Type.displayCutout())
            val pad = intArrayOf(i.left, i.top, i.right, i.bottom)
            return Triple(m.bounds.width() - i.left - i.right, m.bounds.height() - i.top - i.bottom, pad)
        }
        val d = resources.displayMetrics
        return Triple(d.widthPixels, d.heightPixels, intArrayOf(0, 0, 0, 0))
    }

    private fun build(n: JSONObject, w: Int, h: Int): View {
        val kids = n.optJSONArray("k") ?: JSONArray()
        val v: View = when (n.getString("t")) {
            "text" -> TextView(this).also { label(it, n, h) }
            "button" -> Button(this).also { label(it, n, h); it.isAllCaps = false; it.minHeight = 0; it.minimumHeight = 0; it.minWidth = 0; it.minimumWidth = 0; it.stateListAnimator = null }
            "field" -> EditText(this).also { it.hint = n.getString("l"); it.isSingleLine = true; it.setPadding(0, 0, 0, 0); size(it, h) }
            "row" -> LinearLayout(this).apply {
                orientation = LinearLayout.HORIZONTAL
                split(kids, w).forEachIndexed { i, cw -> addView(build(kids.getJSONObject(i), cw, h), ViewGroup.LayoutParams(cw, h)) }
            }
            else -> if (n.has("cols")) grid(kids, n.getInt("cols"), w, h) else LinearLayout(this).apply {
                orientation = LinearLayout.VERTICAL
                split(kids, h).forEachIndexed { i, ch -> addView(build(kids.getJSONObject(i), w, ch), ViewGroup.LayoutParams(w, ch)) }
            }
        }
        if (n.has("id")) v.id = ids.getOrPut(n.getString("id")) { resources.getIdentifier(n.getString("id"), "id", packageName) }
        if (n.has("d")) v.contentDescription = n.getString("d")
        return v
    }

    // single line: a BoringLayout instead of full line breaking, which made the first frame of 2000 views take seconds
    private fun label(t: TextView, n: JSONObject, h: Int) { t.isSingleLine = true; t.text = n.getString("l"); t.setPadding(0, 0, 0, 0); size(t, h) }
    private fun size(t: TextView, h: Int) = t.setTextSize(TypedValue.COMPLEX_UNIT_PX, (h * 0.6f).coerceIn(1f, 32f))

    // lengths of the children along the parent's axis: fixed markers first, the rest by weight
    private fun split(kids: JSONArray, length: Int): List<Int> {
        val fixed = (0 until kids.length()).count { kids.getJSONObject(it).optInt("f") == 1 }
        val rest = length - fixed * markerH
        val weights = (0 until kids.length()).map { kids.getJSONObject(it).let { k -> if (k.optInt("f") == 1) 0.0 else k.optDouble("w", 1.0) } }
        val sum = weights.sum().takeIf { it > 0 } ?: 1.0
        return (0 until kids.length()).map { if (kids.getJSONObject(it).optInt("f") == 1) markerH else (rest * weights[it] / sum).toInt() }
    }

    private fun grid(kids: JSONArray, cols: Int, w: Int, h: Int) = FrameLayout(this).apply {
        val rows = (kids.length() + cols - 1) / cols
        val cw = w / cols
        val ch = if (rows > 0) h / rows else h
        for (i in 0 until kids.length()) {
            addView(build(kids.getJSONObject(i), cw, ch), FrameLayout.LayoutParams(cw, ch).apply {
                leftMargin = (i % cols) * cw
                topMargin = (i / cols) * ch
            })
        }
    }
}
